// found in the species search. What is stored per species is a TAXONOMIC FACT entered by the operator: Latin name,
// family, German and English common name (a name is a fact, not a protected work). A name that is not verified stays
// empty (P-08), for example the German name of a species without an established one.
//
// The table also holds `difficulty` and `standard level`. The schema requires both (NOT NULL, DM-BES-01), so "unknown"
